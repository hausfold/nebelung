#!/usr/bin/env node
// Regenerate the port tables in docs/ports.md AND the port board in README.md,
// both from ports.meta.json.
//
//   node scripts/gen-ports-doc.mjs           # rewrite both in place
//   node scripts/gen-ports-doc.mjs --check   # exit 1 if either is stale (what the test does)
//
// ports.conf says WHICH ports get rendered and from what; ports.meta.json says
// where each one's output has to land and what makes it active. That second
// file is the machine-readable half of what the docs table used to only say in
// prose — a consumer (nebelhaus) reads it from the flake's `ports` output to
// decide which ports it can wire on its own and which ones need a human. The
// docs are generated from it so the two can't drift.
//
// Two outputs, one source:
//   README.md      the board — every port, grouped, each name linking straight
//                  to its own row in the docs table
//   docs/ports.md  the rows — one table per category, output path + how to
//                  install it, each row carrying the anchor the board links to
//
// Row order inside a category follows ports.conf, then any meta-only ports (the
// non-whiskers ones, vscode/stylus) in the order they appear in the JSON.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const BEGIN = "<!-- ports:begin -->";
const END = "<!-- ports:end -->";
const GENERATED = "<!-- Generated by scripts/gen-ports-doc.mjs from ports.meta.json — do not edit by hand. -->";

// The shelves ports sit on, in the order both files present them. `label` is
// what the reader sees; the key is what ports.meta.json stores. A heading of
// the label is what `#anchor` links in the board resolve against, so renaming a
// label moves an anchor — the generator rewrites both sides at once.
export const CATEGORIES = [
  { key: "terminal", label: "terminals" },
  { key: "shell", label: "shell & prompt" },
  { key: "multiplexer", label: "multiplexers" },
  { key: "editor", label: "editors" },
  { key: "git", label: "git" },
  { key: "tui", label: "cli & tui" },
  { key: "app", label: "apps" },
  { key: "web", label: "web" },
];
export const CATEGORY_KEYS = CATEGORIES.map((c) => c.key);

// GitHub prefixes anchors it finds in HTML with `user-content-` and fixes the
// link up client-side, so `docs/ports.md#p-ghostty` lands on the row below.
const anchor = (name) => `p-${name}`;
// Ports the reader has to finish by hand get a marker in the board, explained
// by a legend the generator emits with it.
const MANUAL_MARK = "°";

// How the theme gets on disk.
export const INSTALL_KINDS = ["copy", "merge", "compile", "paste"];
// What makes it the ACTIVE theme once it's there. This is the field that
// decides the tier, because it's the one a rebuild can or can't do for you:
//   path     the destination path is the activation — nothing else to set
//   key      a setting in the tool's own config, which a config manager owns
//   include  an include/source/import line from the tool's rc
//   env      an environment variable pointing at the file (or carrying it)
//   command  a command that has to run once after install
//   mutable  a setting in a file the APP rewrites at runtime, so it has to be
//            patched at activation time rather than symlinked — and the app can
//            clobber it back
//   gui      a human clicks or pastes; there is no file interface at all
export const SELECT_KINDS = ["path", "key", "include", "env", "command", "mutable", "gui"];
export const TIERS = ["auto", "activate", "manual"];
// Where the port's TOOL runs, so a consumer iterating this file doesn't try to
// wire a Wayland terminal on macOS. Most ports list both.
export const PLATFORMS = ["darwin", "linux"];

// The contract. ports.meta.json stores `tier` explicitly so the flake can read
// it verbatim without reimplementing this in Nix; the test asserts every stored
// tier matches what this returns, so the two can't disagree.
export const deriveTier = (entry) => {
  if (entry.select === "gui") return "manual";
  if (entry.select === "mutable" || entry.install === "compile") return "activate";
  return "auto";
};

export const readMeta = () =>
  JSON.parse(readFileSync(join(root, "ports.meta.json"), "utf8"));

// Port names in ports.conf order, deduped — a port can span several lines
// (obsidian's theme + manifest, telegram's four clients).
export const readConfPorts = () => {
  const names = [];
  for (const line of readFileSync(join(root, "ports.conf"), "utf8").split("\n")) {
    const name = line.split("|")[0].trim();
    if (!name || name.startsWith("#")) continue;
    if (!names.includes(name)) names.push(name);
  }
  return names;
};

export const portOrder = (meta = readMeta()) => {
  const conf = readConfPorts().filter((n) => n in meta);
  return [...conf, ...Object.keys(meta).filter((n) => !conf.includes(n))];
};

const cell = (s, what) => {
  if (s.includes("|")) throw new Error(`${what} contains a pipe, which breaks the table: ${s}`);
  return s;
};

// GitHub's own heading-anchor rule, narrow enough for the labels above:
// lowercase, drop anything that isn't a word character or a space, spaces to
// hyphens. "shell & prompt" → "shell--prompt".
export const headingAnchor = (label) =>
  label.toLowerCase().replace(/[^\w -]/g, "").replace(/ /g, "-");

// Ports of one category, in the shared order.
export const portsIn = (key, meta = readMeta()) =>
  portOrder(meta).filter((n) => meta[n].category === key);

// docs/ports.md — one table per category, each row anchored so the README board
// can link a port name straight at its install line.
export const renderTable = (meta = readMeta()) => {
  const all = portOrder(meta);
  const sections = CATEGORIES.flatMap(({ key, label }) => {
    const rows = portsIn(key, meta).map((name) => {
      const p = meta[name];
      const out = "`" + p.path + "`" + (p.pathNote ? ` ${p.pathNote}` : "");
      const title = `<a name="${anchor(name)}"></a>${cell(p.title, name)}`;
      return `| ${title} | ${cell(out, name)} | ${p.tier} | ${cell(p.howto, name)} |`;
    });
    return [
      `### ${label}`,
      "",
      "| Port | Output in `dist/` | Tier | Install |",
      "| --- | --- | --- | --- |",
      ...rows,
      "",
    ];
  });
  const titles = (pred) => all.filter((n) => pred(meta[n])).map((n) => meta[n].title);
  const manual = titles((p) => p.tier === "manual");
  const linuxOnly = titles((p) => !p.platform.includes("darwin"));
  const darwinOnly = titles((p) => !p.platform.includes("linux"));
  return [
    BEGIN,
    GENERATED,
    "",
    ...sections,
    `**${manual.length} of ${all.length} ports can't be installed for you:** ` +
      `${manual.join(", ")}. Everything else is a file drop plus a setting a config ` +
      `manager can own.`,
    "",
    `**${linuxOnly.length + darwinOnly.length} are platform-specific:** ` +
      `Linux only — ${linuxOnly.join(", ")}; macOS only — ${darwinOnly.join(", ")}. ` +
      `The rest list both.`,
    "",
    END,
  ].join("\n");
};

// README.md — the board. Every port, grouped, each name a link to its row in
// the table above. Manual ports carry a marker so the one thing the reader has
// to do by hand is visible before they click.
export const renderBoard = (meta = readMeta()) => {
  const all = portOrder(meta);
  const manualCount = all.filter((n) => meta[n].tier === "manual").length;
  const lines = CATEGORIES.flatMap(({ key, label }) => {
    const names = portsIn(key, meta);
    const links = names.map((n) => {
      const mark = meta[n].tier === "manual" ? MANUAL_MARK : "";
      return `[${meta[n].title}](docs/ports.md#${anchor(n)})${mark}`;
    });
    return [
      `**[${label}](docs/ports.md#${headingAnchor(label)})** · ${names.length}`,
      "",
      links.join(" · "),
      "",
    ];
  });
  return [
    BEGIN,
    GENERATED,
    "",
    ...lines,
    `<sub>${MANUAL_MARK} the app has no file interface for picking a theme — ` +
      `${manualCount} of ${all.length} ports end in a click or a paste. ` +
      `Every link goes to that port's output path and the one line that turns it on.</sub>`,
    "",
    END,
  ].join("\n");
};

const TARGETS = [
  { path: join(root, "docs", "ports.md"), label: "docs/ports.md", render: renderTable },
  { path: join(root, "README.md"), label: "README.md", render: renderBoard },
];

const splice = ({ path, label, render }) => {
  const doc = readFileSync(path, "utf8");
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END);
  if (start === -1 || end === -1) {
    throw new Error(`${label} is missing the ${BEGIN} / ${END} markers`);
  }
  return { label, path, doc, next: doc.slice(0, start) + render() + doc.slice(end + END.length) };
};

// Both generated files with their marked region replaced by fresh output. The
// test imports this and compares against what's on disk, so a stale table or a
// stale board fails `node --test` (and therefore `nix flake check`) rather than
// rotting quietly.
export const renderDocs = () => TARGETS.map(splice);

// Only when run as a script — the test imports the helpers above.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const { label, path, doc, next } of renderDocs()) {
    if (check) {
      if (next !== doc) {
        console.error(`✗ ${label} is stale — run \`node scripts/gen-ports-doc.mjs\``);
        stale = true;
      } else {
        console.log(`✓ ${label} is in sync with ports.meta.json`);
      }
    } else {
      writeFileSync(path, next);
      console.log(`✓ ports → ${label}`);
    }
  }
  if (stale) process.exit(1);
}
